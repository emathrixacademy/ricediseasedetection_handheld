# Page 2: potentiostat


def opamp(c, x, y, name, role, flip=False, below=False):
    """Triangle pointing right, inputs at x, output at x+60. Returns pin coordinates."""
    c.setStrokeColorRGB(*INK)
    c.setFillColorRGB(1, 1, 1)
    c.setLineWidth(1.2)
    p = c.beginPath()
    p.moveTo(x, y + 30)
    p.lineTo(x, y - 30)
    p.lineTo(x + 60, y)
    p.close()
    c.drawPath(p, stroke=1, fill=1)
    plus, minus = (y + 15, y - 15) if not flip else (y - 15, y + 15)
    c.setFillColorRGB(*INK)
    c.setFont("Helvetica-Bold", 9)
    c.drawString(x + 4, plus - 3, "+")
    c.drawString(x + 4, minus - 3, "-")
    ny, ry = (y - 42, y - 52) if below else (y + 46, y + 36)
    c.setFont("Helvetica-Bold", 8)
    c.drawString(x + 2, ny, name)
    c.setFont("Helvetica", 7)
    c.setFillColorRGB(*MUTED)
    c.drawString(x + 2, ry, role)
    return {"+": (x, plus), "-": (x, minus), "out": (x + 60, y)}


def part(c, x, y, label, vertical=False):
    """Resistor/capacitor symbol as a small box with a label."""
    c.setStrokeColorRGB(*INK)
    c.setFillColorRGB(1, 1, 1)
    c.setLineWidth(1)
    if vertical:
        c.rect(x - 4, y - 10, 8, 20, stroke=1, fill=1)
        c.setFont("Helvetica", 6.8)
        c.setFillColorRGB(*INK)
        c.drawString(x + 6, y - 2, label)
    else:
        c.rect(x - 10, y - 4, 20, 8, stroke=1, fill=1)
        c.setFont("Helvetica", 6.8)
        c.setFillColorRGB(*INK)
        c.drawCentredString(x, y + 6, label)


def gnd_sym(c, x, y):
    c.setStrokeColorRGB(*INK)
    c.setLineWidth(1)
    for i, w in enumerate((8, 5, 2)):
        c.line(x - w, y - i * 3, x + w, y - i * 3)


def page_afe(c):
    title(c, "2. Potentiostat - analog front end (ESP32 side)",
          "MCP6004 quad op-amp, 3.3 V single supply. The control amplifier (U1C) holds the "
          "reference electrode at the DAC voltage; the TIA (U1B) holds the working electrode "
          "at virtual ground.")

    # Virtual ground and U1D buffer
    c.setFont("Helvetica-Bold", 8)
    c.setFillColorRGB(*INK)
    c.drawString(60, 470, "3.3 V")
    wire(c, [(70, 465), (70, 450)], "pwr33")
    part(c, 70, 440, "10 k 1%", vertical=True)
    wire(c, [(70, 430), (70, 410), (70, 390)], "bus")
    part(c, 70, 380, "10 k 1%", vertical=True)
    wire(c, [(70, 370), (70, 355)], "bus")
    gnd_sym(c, 70, 355)
    part(c, 110, 395, "100 nF", vertical=True)
    wire(c, [(70, 410), (110, 410), (110, 405)], "bus")
    wire(c, [(110, 385), (110, 370)], "bus")
    gnd_sym(c, 110, 370)
    d = opamp(c, 160, 410, "U1D (12,13,14)", "virtual-ground buffer")
    wire(c, [(110, 410), (130, 410), (130, d["+"][1]), d["+"]], "bus")
    wire(c, [d["out"], (240, 410), (240, 370), (150, 370), (150, d["-"][1]), d["-"]], "bus")
    wire(c, [(240, 410), (300, 410)], "bus", "VGND 1.65 V", dx=-30, dy=4)

    # U1B TIA
    b = opamp(c, 330, 300, "U1B (5,6,7)", "transimpedance amplifier", flip=True, below=True)
    wire(c, [(300, 410), (300, b["+"][1]), b["+"]], "bus")
    wire(c, [(300, 410), (300, 470), (660, 470), (660, 400), (690, 400)], "bus", "AIN3",
         at=3, dx=-8, dy=4)
    # WE input and feedback
    wire(c, [(200, 315), b["-"]], "bus", "WE (working electrode)", dx=-95, dy=4)
    wire(c, [(320, 315), (320, 350), (350, 350)], "bus")
    part(c, 360, 350, "Rf 100 k 1%")
    wire(c, [(370, 350), (400, 350), (400, 300)], "bus")
    wire(c, [(320, 350), (320, 372), (350, 372)], "bus")
    part(c, 360, 372, "Cf 100 pF")
    wire(c, [(370, 372), (400, 372), (400, 350)], "bus")
    wire(c, [b["out"], (690, 300)], "bus", "AIN0   I = (V_AIN0 - V_AIN3) / 100 k",
         at=0, dx=60, dy=4)

    # DAC -> U1C control amplifier -> CE
    block(c, 40, 160, 110, 60, "MCP4725 DAC", ["12-bit, I2C 0x60", "VOUT = VGND - E"])
    cc = opamp(c, 220, 190, "U1C (8,9,10)", "control amplifier")
    wire(c, [(150, 205), cc["+"]], "sig", "VOUT", dx=-10, dy=4)
    part(c, 320, 190, "1 k")
    wire(c, [cc["out"], (310, 190)], "bus")
    wire(c, [(330, 190), (380, 190)], "bus", "CE (counter electrode)", dx=-10, dy=4)
    part(c, 250, 262, "10 nF")
    wire(c, [(200, 175), (200, 262), (240, 262)], "bus")
    wire(c, [(260, 262), (295, 262), (295, 190)], "bus")

    # RE buffer U1A
    a = opamp(c, 470, 120, "U1A (1,2,3)", "reference-electrode buffer")
    wire(c, [(400, 135), a["+"]], "bus", "RE (Ag/AgCl)", dx=-60, dy=4)
    wire(c, [a["out"], (560, 120), (560, 80), (455, 80), (455, a["-"][1]), a["-"]], "bus")
    wire(c, [(560, 120), (690, 120)], "bus", "AIN1", dx=20, dy=4)
    part(c, 330, 80, "10 k")
    wire(c, [(455, 80), (340, 80)], "bus")
    wire(c, [(320, 80), (200, 80), (200, 175), cc["-"]], "bus", "RE feedback", at=1, dx=-60, dy=4)

    # ADS1115
    block(c, 690, 90, 120, 400, "ADS1115 ADC", ["16-bit, I2C 0x49", "GAIN_ONE +/-4.096 V", "",
                                                 "AIN0  TIA output", "AIN1  RE buffer",
                                                 "AIN2  battery / 2", "AIN3  VGND", "",
                                                 "ALERT -> ESP32 GPIO35", "SDA/SCL -> 21/22",
                                                 "4.7 k pull-ups"])
    note(c, ["Supply: MCP6004 pin 4 = 3.3 V, pin 11 = GND, 100 nF at each IC supply pin.",
             "E(WE vs RE) = VGND - VDAC.  H2O2 sweep -0.2 ... +0.6 V -> VDAC 1.85 ... 1.05 V.",
             "Readable current +/-16.5 uA (TIA swing +/-1.65 V / 100 k); beyond +/-15.5 uA = SATURATED.",
             "Previous design drove CE from the DAC through 10 k with no control loop: "
             "RE was not held, so E drifted with the cell current."], 36, 60, 7.4)


