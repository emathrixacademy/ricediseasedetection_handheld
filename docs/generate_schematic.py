    legend(c, [("5 V", "pwr5"), ("3.3 V", "pwr33"), ("Battery", "batt"), ("I2C", "i2c"),
               ("UART", "uart"), ("SPI", "spi"), ("Signal / GPIO", "sig"),
               ("Analog (electrodes)", "bus")], 36, PH - 74)

    # Power column
    block(c, 36, 430, 120, 44, "Solar panel", ["6 V, top of body"])
    block(c, 36, 360, 120, 44, "Solar charge ctrl", ["1S Li-ion charger"])
    block(c, 36, 290, 120, 44, "LiPo 3.7 V", ["1 cell, protected"])
    block(c, 36, 220, 120, 44, "Power switch", ["SPST"])
    block(c, 36, 130, 120, 54, "Boost converter", ["5 V / 5 A out", "(Pi 5 needs 5 A)"])
    block(c, 200, 70, 70, 34, "Fuse 1 A")
    wire(c, [(96, 430), (96, 404)], "pwr5", "6 V", dx=4, dy=-2)
    wire(c, [(96, 360), (96, 334)], "batt", "charge", dx=4, dy=-2)
    wire(c, [(96, 290), (96, 264)], "batt", "3.7 V", dx=4, dy=-2)
    wire(c, [(96, 220), (96, 184)], "batt")
    # Battery sense to ADS1115 AIN2
    wire(c, [(156, 312), (176, 312), (176, 30), (560, 30), (560, 96)], "batt",
         "BATT+ -> 100k/100k divider -> ADS1115 AIN2", at=2, dx=-150, dy=4)

    # Pi 5
    block(c, 330, 300, 170, 150, "Raspberry Pi 5", ["4 GB", "cameras, AI models, fusion,",
                                                     "TFT, database"])
