def page_tft(c):
    title(c, "3. Display - 2.4\" ILI9341 TFT on the Raspberry Pi 5",
          "240 x 320, SPI0 at 32 MHz, write-only. Mounted on the back face of the body. "
          "MISO and the touch pins are not connected.")
    block(c, 60, 140, 170, 330, "Raspberry Pi 5", ["40-pin header", "(physical pin)"])
    block(c, 560, 200, 190, 270, "2.4\" TFT module", ["ILI9341, red PCB"], fill=(0.98, 0.88, 0.88))
    rows = [("3V3  [1]", "VCC", "pwr33"), ("GND  [6]", "GND", "gnd"),
            ("GPIO8 CE0  [24]", "CS", "spi"), ("GPIO24  [18]", "RESET", "sig"),
            ("GPIO25  [22]", "DC", "sig"), ("GPIO10 MOSI  [19]", "SDI (MOSI)", "spi"),
            ("GPIO11 SCLK  [23]", "SCK", "spi")]
    for i, (pi, tft, k) in enumerate(rows):
        y = 420 - i * 30
        c.setFont("Helvetica-Bold", 8)
        c.setFillColorRGB(*INK)
        c.drawRightString(222, y + 3, pi)
        c.drawString(568, y + 3, tft)
        wire(c, [(230, y), (560, y)], k)
    c.setFont("Helvetica", 7.5)
    c.setFillColorRGB(*MUTED)
    c.drawString(568, 205 + 10, "LED (backlight) - see switch")
    c.drawString(568, 205, "SDO, T_CLK, T_CS, T_DIN, T_DO, T_IRQ: n.c.")

    # Backlight switch
    c.setFont("Helvetica-Bold", 9)
    c.setFillColorRGB(*INK)
    c.drawString(270, 190, "Backlight switch (high side)")
    block(c, 300, 90, 90, 40, "2N7002", ["N-MOSFET"])
    block(c, 440, 130, 90, 40, "AO3401", ["P-MOSFET"])
    wire(c, [(230, 110), (300, 110)], "sig", "GPIO18 [12] - 100 R", dx=-40, dy=4)
    part(c, 262, 92, "100 k", vertical=True)
    wire(c, [(262, 110), (262, 102)], "sig")
    wire(c, [(262, 82), (262, 70)], "gnd")
    gnd_sym(c, 262, 70)
    wire(c, [(345, 130), (345, 150), (440, 150)], "sig", "gate", at=1, dx=-20, dy=4)
    part(c, 420, 175, "10 k")
    wire(c, [(410, 175), (395, 175), (395, 150)], "pwr33")
    wire(c, [(430, 175), (485, 175), (485, 170)], "pwr33", "3.3 V (source)", at=0, dx=6, dy=4)
    wire(c, [(530, 150), (560, 150), (560, 215)], "pwr33", "LED", at=1, dx=4, dy=0)
    wire(c, [(345, 90), (345, 70)], "gnd")
    gnd_sym(c, 345, 70)
    note(c, ["GPIO18 high = backlight on (PWM dims it). The backlight draws 30-60 mA;",
             "a Pi GPIO may source about 16 mA, so it only switches the MOSFETs.",
             "No dimming needed: tie LED to 3.3 V and leave out the switch.",
             "Software: luma.lcd ili9341, rotate=1 (portrait); rpi-lgpio on the Pi 5."], 575, 140)


def main():
    c = rcanvas.Canvas(OUT, pagesize=(PW, PH))
    c.setTitle("Rice Disease Handheld Scanner - Wiring Schematic")
    for draw in (page_system, page_afe, page_tft):
        draw(c)
        c.showPage()
    c.save()
    print("Wrote", OUT)


if __name__ == "__main__":
    main()
