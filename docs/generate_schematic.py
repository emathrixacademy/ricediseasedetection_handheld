#!/usr/bin/env python3
"""Generate docs/wiring_schematic.pdf for the Rice Disease Handheld Scanner.

Three landscape A4 pages, drawn with ReportLab:

1. System block diagram: power chain, Pi 5 and its peripherals, ESP32,
   biosensor front end, buttons. Wires are routed orthogonally and never
   pass through a block.
2. Potentiostat (analog front end): MCP4725 DAC, MCP6004 quad op-amp
   (control amplifier, RE buffer, TIA, virtual-ground buffer), ADS1115.
3. 2.4" ILI9341 TFT on the Pi 5's SPI0, with the backlight switch.

Pin data mirrors esp32/src/config.h, pi5/config.py and docs/WIRING.md --
if those change, re-run this script.

    pip install reportlab
    python docs/generate_schematic.py
"""
import os

from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas as rcanvas

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "wiring_schematic.pdf")
PW, PH = landscape(A4)

INK = (0.11, 0.14, 0.13)
MUTED = (0.40, 0.44, 0.43)
FILL = (0.91, 0.95, 0.92)
COL = {
    "pwr5": (0.84, 0.27, 0.27), "pwr33": (0.87, 0.52, 0.00), "gnd": (0.45, 0.48, 0.50),
    "i2c": (0.23, 0.49, 0.85), "uart": (0.18, 0.62, 0.42), "spi": (0.55, 0.30, 0.75),
    "sig": (0.72, 0.50, 0.10), "bus": (0.25, 0.25, 0.25), "batt": (0.60, 0.20, 0.20),
}


def title(c, text, sub):
    c.setFillColorRGB(*INK)
    c.setFont("Helvetica-Bold", 15)
    c.drawString(36, PH - 40, text)
    c.setFont("Helvetica", 9)
    c.setFillColorRGB(*MUTED)
    c.drawString(36, PH - 54, sub)
    c.setFont("Helvetica-Oblique", 7.5)
    c.drawString(36, 20, "Rice Disease Handheld Scanner - eMathrix Technologies - generated by "
                 "docs/generate_schematic.py from esp32/src/config.h, pi5/config.py, docs/WIRING.md")


def block(c, x, y, w, h, name, lines=(), fill=FILL):
    c.setFillColorRGB(*fill)
    c.setStrokeColorRGB(*INK)
    c.setLineWidth(1.1)
    c.roundRect(x, y, w, h, 5, stroke=1, fill=1)
    c.setFillColorRGB(*INK)
    c.setFont("Helvetica-Bold", 9.5)
    c.drawCentredString(x + w / 2, y + h - 13, name)
    c.setFont("Helvetica", 7.2)
    c.setFillColorRGB(*MUTED)
    for i, ln in enumerate(lines):
        c.drawCentredString(x + w / 2, y + h - 25 - i * 9.5, ln)


def wire(c, pts, kind, label=None, at=0, dx=3, dy=3, dash=False):
    """Polyline through ``pts``; optional label near segment ``at``."""
    c.setStrokeColorRGB(*COL[kind])
    c.setLineWidth(1.6)
    if dash or kind == "gnd":
        c.setDash(4, 3)
    p = c.beginPath()
    p.moveTo(*pts[0])
    for q in pts[1:]:
        p.lineTo(*q)
    c.drawPath(p, stroke=1, fill=0)
    c.setDash()
    for q in (pts[0], pts[-1]):
        c.setFillColorRGB(*COL[kind])
        c.circle(q[0], q[1], 1.8, stroke=0, fill=1)
    if label:
        (x0, y0), (x1, y1) = pts[at], pts[at + 1]
        c.setFont("Helvetica", 6.8)
        c.setFillColorRGB(*COL[kind])
        c.drawString((x0 + x1) / 2 + dx, (y0 + y1) / 2 + dy, label)


def legend(c, items, x, y):
    c.setFont("Helvetica", 7.5)
    for i, (lab, k) in enumerate(items):
        xx = x + (i % 4) * 92
        yy = y - (i // 4) * 12
        c.setStrokeColorRGB(*COL[k])
        c.setLineWidth(2.2)
        if k == "gnd":
            c.setDash(4, 3)
        c.line(xx, yy + 3, xx + 18, yy + 3)
        c.setDash()
        c.setFillColorRGB(*INK)
        c.drawString(xx + 22, yy, lab)


def note(c, lines, x, y, size=7.6):
    c.setFont("Helvetica", size)
    c.setFillColorRGB(*INK)
    for i, ln in enumerate(lines):
        c.drawString(x, y - i * (size + 3), ln)


