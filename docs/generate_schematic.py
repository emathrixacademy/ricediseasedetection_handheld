    block(c, 600, 310, 150, 40, "NoIR Camera Module 3", ["+ NIR filter"])
    block(c, 600, 205, 150, 76, "2.4\" TFT ILI9341", ["240 x 320, red module", "SPI0: MOSI 10, SCLK 11,",
                                                     "CS 8, DC 25, RST 24"])
    block(c, 600, 150, 150, 40, "Backlight switch", ["AO3401 + 2N7002"])
    wire(c, [(500, 430), (560, 430), (560, 450), (600, 450)], "sig", "PCIe x1", at=0, dy=4)
    wire(c, [(500, 410), (570, 410), (570, 390), (600, 390)], "sig", "CSI-0", at=0, dy=4)
    wire(c, [(500, 330), (600, 330)], "sig", "CSI-1", dy=4)
    wire(c, [(500, 312), (575, 312), (575, 243), (600, 243)], "spi")
    wire(c, [(675, 205), (675, 190)], "pwr33", "LED", dx=4, dy=-4)
    wire(c, [(500, 304), (585, 304), (585, 170), (600, 170)], "sig", "GPIO18", at=1, dx=4, dy=-40)

    # ESP32
    block(c, 330, 66, 170, 110, "ESP32 DevKit", ["DPV sweep, buttons, LED,", "battery, UART2"])
    wire(c, [(400, 300), (400, 176)], "uart")
    wire(c, [(430, 300), (430, 176)], "uart")
    c.setFont("Helvetica", 6.8)
    c.setFillColorRGB(*COL["uart"])
    c.drawString(436, 250, "UART 115200:")
    c.drawString(436, 241, "Pi GPIO14 TX -> RX2 (16)")
    c.drawString(436, 232, "Pi GPIO15 RX <- TX2 (17)")

    # Buttons and LED
    block(c, 200, 190, 100, 70, "Buttons", ["SCAN  GPIO32", "MODE  GPIO33", "MENU  GPIO34*"])
    block(c, 200, 120, 80, 34, "Status LED", ["GPIO27, 220 R"])
    wire(c, [(300, 225), (315, 225), (315, 160), (330, 160)], "sig")
    wire(c, [(280, 137), (330, 137)], "sig")

    # Front end and electrodes
    block(c, 530, 60, 150, 70, "Potentiostat (AFE)", ["MCP4725 DAC 0x60", "MCP6004 quad op-amp",
                                                       "ADS1115 ADC 0x49"])
    block(c, 710, 60, 100, 70, "Needle electrodes", ["WE  working", "RE  Ag/AgCl", "CE  counter"])
    wire(c, [(500, 110), (530, 110)], "i2c", "I2C 21/22", dx=-22, dy=4)
    wire(c, [(500, 80), (530, 80)], "sig", "ALERT 35", dx=-24, dy=-10)
    wire(c, [(680, 105), (710, 105)], "bus", "WE", dx=-6, dy=4)
    wire(c, [(680, 95), (710, 95)], "bus")
    wire(c, [(680, 85), (710, 85)], "bus", "RE CE", dx=-10, dy=-11)

    note(c, ["* GPIO34 is input-only: external 10 k pull-up to 3.3 V.",
             "One star ground for Pi 5, ESP32, converter and front end.",
             "Details: page 2 (front end), page 3 (TFT)."], 330, 500)


